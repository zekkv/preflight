/**
 * The button classes, with conflicts resolved. `cva` alone only concatenates, so the base
 * `border-transparent` / `text-sm` would beat a variant's `border-input` / `text-base` by CSS
 * source order. Use this to style a link (`<a>`, router `<Link>`) as a button.
 */
function buttonVariants(props?: Parameters<typeof buttonVariantsBase>[0]) {
  return cn(buttonVariantsBase(props));
}

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariantsBase>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={buttonVariants({ variant, size, className })}
      {...props}
    />
  );
}

export { Button, buttonVariants };
